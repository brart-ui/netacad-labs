john = 3
mary = 5
adam = 6

print(john, mary, adam, sep=",")

total_apples = john + mary + adam
print(total_apples)
print("Total number of apples:", total_apples)

extra_apples = 4
people = 3

print("After adding apples:", total_apples + extra_apples)
print("After eating apples:", total_apples - extra_apples)
print("Double the apples:", total_apples * 2)
print("Apples per person:", total_apples / people)
print("Whole apples per person:", total_apples // people)
print("Apples left over:", total_apples % people)
